"""Put napari's shared colours in front of the custom mystmd overrides.

Run via: python docs/_scripts/copy_theme_css.py
Called automatically by: pixi run _copy-css (as a dependency of build/start).

mystmd takes one stylesheet (`style:` in myst.yml), so the two files are
joined into one.

Sources (in version control):
  docs/_resources/brand/napari-tokens.css  napari's colours, copied from
                                           napari-sphinx-theme's brand folder
  docs/_resources/_custom.css              this site's overrides
Output (gitignored, regenerated each build):
  docs/_resources/napari-theme.css
"""

import pathlib

resources = pathlib.Path('docs/_resources')
tokens = (resources / 'brand' / 'napari-tokens.css').read_text(encoding='utf-8')
custom = (resources / '_custom.css').read_text(encoding='utf-8')

output = (
    '/* Generated by docs/_scripts/copy_theme_css.py. DO NOT EDIT:\n'
    ' * edit _resources/_custom.css, or update brand/napari-tokens.css. */\n\n'
    + tokens
    + '\n\n/* Custom overrides for the mystmd book-theme */\n\n'
    + custom
)

out_path = resources / 'napari-theme.css'
out_path.write_text(output, encoding='utf-8')
print(f'Generated {out_path} ({out_path.stat().st_size} bytes)')
